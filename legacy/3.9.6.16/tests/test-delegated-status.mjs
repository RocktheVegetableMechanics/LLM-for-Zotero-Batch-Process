import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const src=fs.readFileSync(new URL('../src/extension/content/scripts/llmforzotero.js',import.meta.url),'utf8');
const start=src.indexOf('  // src/agent/contracts/actionEvaluation.ts');
const end=src.indexOf('\n  // ',start+5);
const ctx=vm.createContext({__esm:()=>()=>{},receiptVerified:r=>r.verification==='verified'&&r.status==='applied'});
vm.runInContext(src.slice(start,end),ctx);
const receipt={operation:'zotero_script_execute',executionAuthority:'external_runtime',status:'observed',verification:'execution_only',proofDomain:'execution',requestedTargets:[],appliedTargets:[],alreadySatisfiedTargets:[]};
const six=Array.from({length:6},()=>({...receipt}));
const result=ctx.evaluatePreparedActionContract({},six);
assert.equal(result.state,'unverified');
assert.match(result.failure,/6 calls/);assert.equal((result.failure.match(/Zotero script:/g)||[]).length,1);
assert.ok(!result.failure.includes('[Action status:'));
assert.match(result.failure,/not independently verified/);
const failed=ctx.evaluatePreparedActionContract({},[{...receipt,status:'failed'}]);assert.equal(failed.state,'failed');assert.match(failed.failure,/failed/);
const cancelled=ctx.evaluatePreparedActionContract({},[{...receipt,status:'cancelled'}]);assert.equal(cancelled.state,'cancelled');
const verified={...receipt,status:'applied',verification:'verified'};
assert.equal(ctx.evaluatePreparedActionContract({},[verified]).state,'satisfied');
assert.equal(ctx.evaluatePreparedActionContract({},[verified,receipt]).state,'partial');
assert.match(ctx.formatReceiptStatus(six),/execution_only/,'detailed receipts remain available');
console.log('PASS: repeated delegated status grouped; unverified/failed/cancelled/partial states unchanged; detailed receipts preserved.');
